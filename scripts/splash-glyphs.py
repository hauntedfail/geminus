#!/usr/bin/env python3
"""Write internal/splash/glyphs.go: how much of each part of its cell every
printable ASCII character fills.

The splash picks, for each cell of the logo, the character whose shape is
closest to that part of the picture. This measures the shapes once, from a
monospaced font, so geminus itself needs no font and no image library.

    python3 scripts/splash-glyphs.py /path/to/IBMPlexMono-Regular.otf

Needs Pillow. The table depends on the font only a little: the characters of
monospaced fonts are drawn alike.
"""
import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont

SUB_W, SUB_H = 4, 6  # parts per cell: across, down
SIZE = 96  # px per em while measuring


def main() -> None:
    font_path = sys.argv[1]
    font = ImageFont.truetype(font_path, SIZE)
    ascent, descent = font.getmetrics()
    cell_w = round(font.getlength("M"))
    cell_h = ascent + descent
    rows = []
    for code in range(33, 127):
        im = Image.new("L", (cell_w, cell_h), 0)
        ImageDraw.Draw(im).text((0, 0), chr(code), font=font, fill=255)
        small = im.resize((SUB_W, SUB_H), Image.Resampling.BOX)
        rows.append((code, list(small.tobytes())))
    out = [
        "// Code generated by scripts/splash-glyphs.py; DO NOT EDIT.",
        "",
        "package splash",
        "",
        "// subW by subH parts of a cell are told apart when a character is chosen.",
        f"const subW, subH = {SUB_W}, {SUB_H}",
        "",
        "// glyphInk says, for each printable character, how much of each part of",
        "// its cell it fills (0..255), row after row.",
        f"// Measured from {pathlib.Path(font_path).name}; the cell is {cell_w} by {cell_h} at {SIZE} px.",
        "var glyphInk = [...]struct {",
        "\tch  byte",
        "\tink [subW * subH]uint8",
        "}{",
    ]
    for code, values in rows:
        name = {39: "'\\''", 92: "'\\\\'"}.get(code, f"'{chr(code)}'")
        out.append(f"\t{{{name}, [subW * subH]uint8{{{', '.join(str(v) for v in values)}}}}},")
    out.append("}")
    target = pathlib.Path(__file__).resolve().parent.parent / "internal" / "splash" / "glyphs.go"
    target.write_text("\n".join(out) + "\n")
    print(f"wrote {target} ({len(rows)} characters, cell {cell_w}x{cell_h})")


if __name__ == "__main__":
    main()
