// Package agent provides a common launch interface for Claude, Hermes, and arbitrary
// commands.
//
// It encapsulates backend-specific session keys and argument lists. It neither starts child
// processes nor accesses credentials.
package agent

import (
	"errors"
	"fmt"
	"os/exec"
	"strings"
)

const (
	// DefaultName identifies the backend used when neither --agent nor the configuration
	// selects one.
	DefaultName = "claude"
	// GenericName identifies the backend that runs an arbitrary command as given.
	GenericName = "cmd"
)

var (
	// ErrNoResume indicates that the backend cannot resume a session.
	ErrNoResume = errors.New("agent does not support resume")
	// ErrNoOneshot indicates that the backend does not support one-shot execution.
	ErrNoOneshot = errors.New("agent does not support one-shot prompts")
	// ErrUnknownAgent indicates that no backend is registered under the given name.
	ErrUnknownAgent = errors.New("unknown agent")
	// ErrNotInstalled indicates that the backend executable could not be found.
	ErrNotInstalled = errors.New("agent binary not found")
	// ErrInvalidKey indicates that the session key is invalid for this backend.
	ErrInvalidKey = errors.New("invalid agent session key")
	// ErrNoCommand indicates that no command was supplied.
	ErrNoCommand = errors.New("no command given")
	// ErrNoPrompt indicates that the one-shot prompt is empty.
	ErrNoPrompt = errors.New("prompt is empty")
	// ErrInvalidPrompt indicates that the prompt cannot be passed unchanged as an agent
	// argument.
	ErrInvalidPrompt = errors.New("invalid prompt")
)

// KeyKind identifies the type of session key, stored as agent_session.kind in session.json.
type KeyKind string

const (
	// KeyNone means the backend has no session key and cannot resume.
	KeyNone KeyKind = "none"
	// KeyUUID denotes a UUIDv4 generated by geminus for Claude.
	KeyUUID KeyKind = "uuid"
	// KeyName denotes a Hermes session name.
	KeyName KeyKind = "name"
)

// SessionKey identifies a session on the agent side.
type SessionKey struct {
	Kind  KeyKind
	Value string
}

// Capabilities describes the features a backend supports.
type Capabilities struct {
	// Resume reports whether the backend can resume the same conversation.
	Resume bool `json:"resume"`
	// Oneshot reports whether the backend can run a single noninteractive exchange.
	Oneshot bool `json:"oneshot"`
	// SessionKey identifies the type of key used to resume a session.
	SessionKey KeyKind `json:"session_key"`
}

// Request holds the inputs for building an argument list.
type Request struct {
	// Key is the session key returned by NewKey.
	Key SessionKey
	// Resume selects whether to resume the conversation identified by Key or start a new one
	// with that key.
	Resume bool
	// Args holds the positional arguments to run: the initial prompt for Claude or Hermes, or
	// the command line for cmd.
	Args []string
}

// Adapter defines how to launch a backend.
type Adapter interface {
	// Name returns the name accepted by --agent.
	Name() string
	// Binary names the executable to look up on PATH. The cmd backend returns an empty string.
	Binary() string
	Capabilities() Capabilities
	// NewKey builds a session key for the given geminus session ID. If fresh is true (--fresh),
	// reusing an ID yields a different key.
	NewKey(geminusID string, fresh bool) (SessionKey, error)
	// Interactive builds the argument list for an interactive session running on a PTY.
	Interactive(req Request) ([]string, error)
	// Oneshot builds the argument list to send prompt once and exit. It ignores req.Args.
	Oneshot(req Request, prompt string) ([]string, error)
}

// adapters lists registered backends in the order used for help and suggestions.
func adapters() []Adapter {
	return []Adapter{claudeAdapter{}, hermesAdapter{}, genericAdapter{}}
}

// All returns the registered adapters.
func All() []Adapter { return adapters() }

// Names returns the registered backend names.
func Names() []string {
	all := adapters()
	names := make([]string, 0, len(all))
	for _, a := range all {
		names = append(names, a.Name())
	}
	return names
}

// UnknownAgentError records the unknown backend name and the available alternatives.
type UnknownAgentError struct {
	Name  string
	Known []string
}

func (e *UnknownAgentError) Error() string {
	return fmt.Sprintf("unknown agent %q (available: %s)", e.Name, strings.Join(e.Known, ", "))
}

// Is makes errors.Is(err, ErrUnknownAgent) report true.
func (e *UnknownAgentError) Is(target error) bool { return target == ErrUnknownAgent }

// Lookup returns the adapter for name. For unknown names, it returns an *UnknownAgentError
// listing the alternatives.
func Lookup(name string) (Adapter, error) {
	for _, a := range adapters() {
		if a.Name() == name {
			return a, nil
		}
	}
	return nil, &UnknownAgentError{Name: name, Known: Names()}
}

// Detection holds the result for one backend for use by geminus agents and doctor.
type Detection struct {
	Name         string       `json:"name"`
	Binary       string       `json:"binary,omitempty"`
	Path         string       `json:"path,omitempty"`
	Found        bool         `json:"found"`
	Capabilities Capabilities `json:"capabilities"`
	Error        string       `json:"error,omitempty"`
}

// Detect looks up the backend executable on PATH. The cmd backend has no binary of its own
// and is always reported as found.
func Detect(a Adapter) Detection {
	d := Detection{Name: a.Name(), Binary: a.Binary(), Capabilities: a.Capabilities()}
	if d.Binary == "" {
		d.Found = true
		return d
	}
	path, err := LookPath(d.Binary)
	if err != nil {
		d.Error = err.Error()
		return d
	}
	d.Path = path
	d.Found = true
	return d
}

// DetectAll checks all registered backends.
func DetectAll() []Detection {
	all := adapters()
	out := make([]Detection, 0, len(all))
	for _, a := range all {
		out = append(out, Detect(a))
	}
	return out
}

// LookPath searches PATH for binary and returns ErrNotInstalled if it is missing.
func LookPath(binary string) (string, error) {
	path, err := exec.LookPath(binary)
	if err != nil {
		return "", fmt.Errorf("%w: %q (%v)", ErrNotInstalled, binary, err)
	}
	return path, nil
}

// ResolveArgv returns a copy of argv with argv[0] resolved against PATH so missing
// executables are detected before launch.
func ResolveArgv(argv []string) ([]string, error) {
	if len(argv) == 0 || argv[0] == "" {
		return nil, ErrNoCommand
	}
	path, err := LookPath(argv[0])
	if err != nil {
		return nil, err
	}
	return append([]string{path}, argv[1:]...), nil
}

// joinPrompt combines the positional arguments to run into one prompt.
func joinPrompt(args []string) string {
	return strings.TrimSpace(strings.Join(args, " "))
}

// checkPrompt validates a one-shot prompt and returns ErrNoPrompt for an empty one.
func checkPrompt(prompt string) error {
	if strings.TrimSpace(prompt) == "" {
		return ErrNoPrompt
	}
	return checkPromptArg(prompt)
}

// checkPromptArg rejects prompts that the agent might parse as flags. A prompt starting
// with a dash (e.g. "--dangerously-skip-permissions") could be interpreted as a flag even
// as a positional argument or the value of -q. Reject it rather than silently changing its
// meaning.
func checkPromptArg(prompt string) error {
	if strings.HasPrefix(strings.TrimSpace(prompt), "-") {
		return fmt.Errorf("%w: a prompt must not start with \"-\" (the agent would read it as a flag)", ErrInvalidPrompt)
	}
	return nil
}
